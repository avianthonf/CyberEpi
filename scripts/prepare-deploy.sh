#!/usr/bin/env bash
# CyberEpi Deployment Preparation Script
# Generates .env.production with secure credentials for single-host deployment
#
# Usage: scripts/prepare-deploy.sh [output_path]
#   output_path: Optional path for .env file (default: .env.production)

set -euo pipefail
set -o noclobber
umask 077

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

OUTPUT_PATH="${1:-.env.production}"

# Validate output path
if [[ "$OUTPUT_PATH" != /* ]]; then
    # Relative path - make it relative to repo root
    OUTPUT_PATH="$REPO_ROOT/$OUTPUT_PATH"
fi

echo "Preparing CyberEpi for single-host deployment..."

# Check for openssl
if ! command -v openssl &> /dev/null; then
    echo "Error: openssl required for password generation"
    exit 1
fi

# Check for existing file
if [ -f "$OUTPUT_PATH" ]; then
    echo "Error: $OUTPUT_PATH already exists"
    echo "   Will not overwrite existing credentials"
    echo "   Remove or rename existing file first"
    exit 1
fi

# Generate secure random passwords
echo "Generating secure credentials..."
POSTGRES_PASSWORD=$(openssl rand -hex 24)
KEYCLOAK_ADMIN_PASSWORD=$(openssl rand -hex 16)

# Create output file (umask 077 ensures 600)
echo "Creating $OUTPUT_PATH..."
cat > "$OUTPUT_PATH" << EOF
# CyberEpi Production Environment Configuration
# Generated by scripts/prepare-deploy.sh
#
# WARNING: This file contains secrets. Do not commit to version control.

# Database
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}

# Authentication
KEYCLOAK_REALM=cyberepi
KEYCLOAK_CLIENT_ID=cyberepi-services
KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=${KEYCLOAK_ADMIN_PASSWORD}

# Service Configuration
LOG_LEVEL=INFO
MAX_PRIVACY_BUDGET=10.0

# External APIs (optional)
OPENFDA_API_URL=https://api.fda.gov/drug/label.json
RXNORM_API_URL=https://rxnav.nlm.nih.gov/REST

# Push Notifications (optional - leave empty to disable)
FIREBASE_CREDENTIALS_PATH=
APNS_KEY_PATH=
APNS_KEY_ID=
APNS_TEAM_ID=
APNS_BUNDLE_ID=com.cyberepi.patient

# Published Ports (defaults for standard deployment)
POSTGRES_PORT=5432
REDIS_PORT=6379
KAFKA_PORT=9092
KEYCLOAK_PORT=8080
KONG_PORT=8000
USER_SERVICE_PORT=8001
SYMPTOM_SERVICE_PORT=8002
PRESCRIPTION_SERVICE_PORT=8003
NOTIFICATION_SERVICE_PORT=8004
EPI_ENGINE_PORT=8005
PRIVACY_SERVICE_PORT=8006
EOF

echo "Created $OUTPUT_PATH (mode 0600)"
echo ""
echo "Deployment preparation complete"
echo ""
echo "DEPLOYMENT COMMANDS"
echo ""
echo "Build images:"
echo "  make build ENV_FILE=\"$OUTPUT_PATH\""
echo ""
echo "Start stack:"
echo "  make up ENV_FILE=\"$OUTPUT_PATH\""
echo ""
echo "Check health:"
echo "  make status ENV_FILE=\"$OUTPUT_PATH\""
echo "  make smoke"
echo ""
echo "View logs:"
echo "  make logs ENV_FILE=\"$OUTPUT_PATH\""
echo ""
echo "Stop stack:"
echo "  make down ENV_FILE=\"$OUTPUT_PATH\""
echo ""
echo "See DEPLOYMENT.md for full documentation"
